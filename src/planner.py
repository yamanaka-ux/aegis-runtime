import socket
from typing import Any, Dict, List, Literal, Optional
from google import genai
from google.genai import types
from pydantic import BaseModel, Field

# Force IPv4 for Google's API host to prevent Ubuntu IPv6 socket stalls
_ORIGINAL_GETADDRINFO = socket.getaddrinfo


def _ipv4_only_getaddrinfo(host, port, family=0, type=0, proto=0, flags=0):
    if isinstance(host, str) and "googleapis.com" in host and family in (0, socket.AF_UNSPEC):
        family = socket.AF_INET
    return _ORIGINAL_GETADDRINFO(host, port, family, type, proto, flags)


socket.getaddrinfo = _ipv4_only_getaddrinfo


class ActionParams(BaseModel):
    amount: Optional[float] = Field(None, description="Dollar amount for allocate_budget")
    campaign_id: Optional[str] = Field(None, description="Campaign identifier for launch_campaign")
    cost: Optional[float] = Field(None, description="Dollar cost for launch_campaign")
    sku: Optional[str] = Field(None, description="Product SKU code for update_price")
    new_price: Optional[float] = Field(None, description="New dollar price for update_price")


class PlannedStep(BaseModel):
    action: Literal["allocate_budget", "launch_campaign", "update_price"]
    params: ActionParams


class AgentPlanResponse(BaseModel):
    reasoning: str = Field(description="Short explanation of the strategy behind these steps")
    steps: List[PlannedStep]


class GeminiPlanner:
    """Low-latency probabilistic AI planner with automatic multi-model fallback."""

    def __init__(self, model_chain: Optional[List[str]] = None):
        # 10-second hard timeout + zero slow SDK background retries
        self.client = genai.Client(
            http_options=types.HttpOptions(
                timeout=10000,
                retry_options=types.HttpRetryOptions(attempts=1),
            )
        )
        self.model_chain = model_chain or [
            "gemini-3.5-flash-lite",
            "gemini-3.7-flash",
            "gemini-3.8-flash",
        ]

    def generate_plan(self, user_goal: str, current_state: Dict[str, Any]) -> List[Dict[str, Any]]:
        system_instruction = (
            "You are an autonomous e-commerce operations agent. "
            "Given a user goal and the current system state, output a sequential list of actions. "
            "Available tools:\n"
            "1. allocate_budget(amount: float) - moves money from budget_remaining to allocated_pool.\n"
            "2. launch_campaign(campaign_id: str, cost: float) - deducts cost from budget_remaining and activates campaign.\n"
            "3. update_price(sku: str, new_price: float) - updates the catalog price of an existing SKU.\n"
            "Always follow the user's requested numbers faithfully."
        )

        prompt = f"Current System State:\n{current_state}\n\nUser Goal:\n{user_goal}"

        last_error: Optional[Exception] = None
        for model_name in self.model_chain:
            print(f"⏳ Trying model '{model_name}'...", flush=True)
            try:
                response = self.client.models.generate_content(
                    model=model_name,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        system_instruction=system_instruction,
                        response_mime_type="application/json",
                        response_schema=AgentPlanResponse,
                        thinking_config=types.ThinkingConfig(thinking_level="LOW"),
                    ),
                )
                parsed_plan: AgentPlanResponse = response.parsed
                print(f"✅ Plan generated by '{model_name}'")
                print(f"🧠 [Reasoning]: {parsed_plan.reasoning}\n", flush=True)

                return [
                    {
                        "action": step.action,
                        "params": step.params.model_dump(exclude_none=True),
                    }
                    for step in parsed_plan.steps
                ]
            except Exception as err:
                print(f"⚠️ '{model_name}' failed ({err}). Failing over...", flush=True)
                last_error = err

        raise RuntimeError(f"All models in fallback chain failed. Last error: {last_error}")
